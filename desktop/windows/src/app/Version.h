// Shared by the C++ compiler, resource compiler and build validation.
#pragma once

#define TELIPHONES_VERSION_MAJOR 0
#define TELIPHONES_VERSION_MINOR 8
#define TELIPHONES_VERSION_PATCH 2
#define TELIPHONES_VERSION_BUILD 0

#define TELIPHONES_STRINGIFY_IMPL(value) #value
#define TELIPHONES_STRINGIFY(value) TELIPHONES_STRINGIFY_IMPL(value)
#define TELIPHONES_VERSION_BASE \
    TELIPHONES_STRINGIFY(TELIPHONES_VERSION_MAJOR) "." \
    TELIPHONES_STRINGIFY(TELIPHONES_VERSION_MINOR) "." \
    TELIPHONES_STRINGIFY(TELIPHONES_VERSION_PATCH)
#define TELIPHONES_VERSION_STRING TELIPHONES_VERSION_BASE
#define TELIPHONES_VERSION_NUMERIC \
    TELIPHONES_VERSION_MAJOR,TELIPHONES_VERSION_MINOR,TELIPHONES_VERSION_PATCH,TELIPHONES_VERSION_BUILD
#define TELIPHONES_VERSION_FILE_STRING \
    TELIPHONES_VERSION_BASE "." TELIPHONES_STRINGIFY(TELIPHONES_VERSION_BUILD)
